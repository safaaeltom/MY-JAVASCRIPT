// Math object
console.log(Math);
console.log(Math.PI);
console.log(Math.E);

const area = 7.6;

console.log(Math.round(area)); // to the nearest whole integer
console.log(Math.floor(area)); // rounds it down
console.log(Math.ceil(area)); // rounds it up
console.log(Math.trunc(area)); // takes away the decimal

